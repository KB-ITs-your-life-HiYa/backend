-- 행정표준코드(법정동코드 기준) 시/도·시/군/구 참조 테이블.
-- 출처: 행정안전부 행정동 경계 데이터(raqoon886/Local_HangJeongDong) 를 가공하고,
-- code.go.kr 행정표준코드관리시스템의 최신 개편 내역을 반영했다.
--
-- member(거주지역)와 subsidy_region(지원금 대상지역)이 공통으로 참조하는
-- 코드 테이블이라 member/benefit 어느 도메인 소유도 아닌 공통 영역에 둔다.
--
-- 이름 표기 규칙:
--   1. 시/도명은 2026년 개편 후 기준이다 (강원특별자치도, 전북특별자치도 등).
--   2. 2026-07-01 전남광주통합특별시(코드 12) 출범을 반영했다.
--      기존 광주광역시(29)·전라남도(46) 소속이던 27개 시/구/군 코드가
--      코드 12 산하로 바뀌었다. 출처: 행정안전부
--      '행정기관(행정동) 및 관할구역(법정동) 변경 상세내역(전남광주통합특별시)', 2026-06-22.
--   3. 시/군/구명은 원본 raqoon886 데이터가 공백 없이 붙여 쓰지만(예: 수원시팔달구),
--      마이홈포털 응답과 member 시드 데이터가 공백을 쓰므로(예: '수원시 팔달구')
--      이 테이블도 공백을 넣어 실제 연동 데이터에 맞췄다.
--   4. '중구', '동구' 처럼 시/군/구 이름만으로는 여러 시/도에 중복되는 이름이
--      있다(각 6개). 이름만으로 조회하지 말고 반드시 sido_code 와 함께 조회할 것.

CREATE TABLE sido (
    code VARCHAR(2) PRIMARY KEY,
    name VARCHAR(20) NOT NULL
);

CREATE TABLE sigungu (
    code      VARCHAR(5) PRIMARY KEY,
    sido_code VARCHAR(2) NOT NULL REFERENCES sido (code),
    name      VARCHAR(20) NOT NULL
);

